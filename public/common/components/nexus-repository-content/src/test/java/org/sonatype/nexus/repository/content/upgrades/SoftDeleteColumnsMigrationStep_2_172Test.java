package org.sonatype.nexus.repository.content.upgrades;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.util.Optional;

import org.sonatype.nexus.datastore.api.DataSession;
import org.sonatype.nexus.repository.content.store.AssetDAO;
import org.sonatype.nexus.testdb.DataSessionRule;

import org.junit.After;
import org.junit.Before;
import org.junit.Rule;
import org.junit.Test;

import static org.hamcrest.CoreMatchers.is;
import static org.hamcrest.MatcherAssert.assertThat;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;
import static org.sonatype.nexus.datastore.api.DataStoreManager.DEFAULT_DATASTORE_NAME;

public class SoftDeleteColumnsMigrationStep_2_172Test
{
  // tables are created WITHOUT deleted_on/deleted_by so the migration has work to do
  private static final String CREATE_ASSET = "CREATE TABLE IF NOT EXISTS {format}_asset (" +
      "asset_id INT GENERATED BY DEFAULT AS IDENTITY, repository_id INT, path VARCHAR);";

  private static final String CREATE_ASSET_BLOB = "CREATE TABLE IF NOT EXISTS {format}_asset_blob (" +
      "asset_blob_id INT GENERATED BY DEFAULT AS IDENTITY);";

  private static final String CREATE_COMPONENT = "CREATE TABLE IF NOT EXISTS {format}_component (" +
      "component_id INT GENERATED BY DEFAULT AS IDENTITY, repository_id INT, namespace VARCHAR, name VARCHAR);";

  @Rule
  public DataSessionRule sessionRule = new DataSessionRule(DEFAULT_DATASTORE_NAME)
      .access(AssetDAO.class);

  private DataSession<?> session;

  private SoftDeleteColumnsMigrationStep_2_172 migrationStep;

  @Before
  public void setUp() {
    migrationStep = new SoftDeleteColumnsMigrationStep_2_172();
    session = sessionRule.openSession(DEFAULT_DATASTORE_NAME);
  }

  @After
  public void cleanup() {
    session.close();
  }

  @Test
  public void version_isAnchor() {
    assertThat(migrationStep.version(), is(Optional.of("2.172")));
  }

  @Test
  public void migrate_addsColumnsToAssetAndComponentTables() throws Exception {
    create(CREATE_ASSET, "maven2");
    create(CREATE_COMPONENT, "maven2");

    try (Connection connection = sessionRule.openConnection(DEFAULT_DATASTORE_NAME)) {
      migrationStep.migrate(connection);

      assertTrue(columnExists(connection, "maven2_asset", "deleted_on"));
      assertTrue(columnExists(connection, "maven2_asset", "deleted_by"));
      assertTrue(columnExists(connection, "maven2_component", "deleted_on"));
      assertTrue(columnExists(connection, "maven2_component", "deleted_by"));
    }
  }

  @Test
  public void migrate_excludesAssetBlobTables() throws Exception {
    create(CREATE_ASSET_BLOB, "maven2");

    try (Connection connection = sessionRule.openConnection(DEFAULT_DATASTORE_NAME)) {
      migrationStep.migrate(connection);

      assertFalse(columnExists(connection, "maven2_asset_blob", "deleted_on"));
      assertFalse(columnExists(connection, "maven2_asset_blob", "deleted_by"));
    }
  }

  @Test
  public void migrate_isIdempotent() throws Exception {
    create(CREATE_ASSET, "maven2");

    try (Connection connection = sessionRule.openConnection(DEFAULT_DATASTORE_NAME)) {
      migrationStep.migrate(connection);
      migrationStep.migrate(connection);

      assertTrue(columnExists(connection, "maven2_asset", "deleted_on"));
      assertTrue(columnExists(connection, "maven2_asset", "deleted_by"));
    }
  }

  @Test
  public void migrate_noTables_doesNotThrow() throws Exception {
    try (Connection connection = sessionRule.openConnection(DEFAULT_DATASTORE_NAME)) {
      migrationStep.migrate(connection);
    }
  }

  private void create(final String ddl, final String formatName) throws Exception {
    try (Connection connection = sessionRule.openConnection(DEFAULT_DATASTORE_NAME)) {
      PreparedStatement ps = connection.prepareStatement(ddl.replaceAll("\\{format\\}", formatName));
      ps.execute();
    }
  }

  private boolean columnExists(
      final Connection conn,
      final String tableName,
      final String columnName) throws Exception
  {
    String sql = "SELECT * FROM INFORMATION_SCHEMA.COLUMNS WHERE UPPER(TABLE_NAME) = ? AND UPPER(COLUMN_NAME) = ?";
    try (PreparedStatement statement = conn.prepareStatement(sql)) {
      statement.setString(1, tableName.toUpperCase());
      statement.setString(2, columnName.toUpperCase());
      try (ResultSet results = statement.executeQuery()) {
        return results.next();
      }
    }
  }
}
