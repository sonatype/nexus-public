package org.sonatype.nexus.repository.content.upgrades;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.util.Arrays;
import java.util.Collections;

import org.sonatype.nexus.datastore.api.DataSession;
import org.sonatype.nexus.repository.Format;
import org.sonatype.nexus.repository.content.store.ComponentDAO;
import org.sonatype.nexus.testdb.DataSessionRule;

import org.junit.After;
import org.junit.Before;
import org.junit.Rule;
import org.junit.Test;
import org.junit.runner.RunWith;
import org.mockito.Mock;
import org.mockito.junit.MockitoJUnitRunner;

import static org.hamcrest.CoreMatchers.is;
import static org.hamcrest.CoreMatchers.not;
import static org.hamcrest.MatcherAssert.assertThat;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;
import static org.mockito.Mockito.when;
import static org.sonatype.nexus.datastore.api.DataStoreManager.DEFAULT_DATASTORE_NAME;

@RunWith(MockitoJUnitRunner.Silent.class)
public class ComponentSoftDeleteRepeatableMigrationStepTest
{
  // Columns are added by the versioned SoftDeleteColumnsMigrationStep_2_172 before this (repeatable) index
  // step runs, so the test table is created WITH them to mirror that ordering.
  private static final String CREATE_COMPONENT_TABLE = "CREATE TABLE IF NOT EXISTS {format}_component (" +
      "component_id INT GENERATED BY DEFAULT AS IDENTITY, " +
      "repository_id INT, " +
      "namespace VARCHAR, " +
      "name VARCHAR, " +
      "deleted_on TIMESTAMP WITH TIME ZONE, " +
      "deleted_by VARCHAR(200)" +
      ");";

  // A table that predates the soft-delete columns, to exercise the defensive columnExists guard.
  private static final String CREATE_COMPONENT_TABLE_NO_SOFT_DELETE =
      "CREATE TABLE IF NOT EXISTS {format}_component (" +
          "component_id INT GENERATED BY DEFAULT AS IDENTITY, " +
          "repository_id INT, " +
          "namespace VARCHAR, " +
          "name VARCHAR" +
          ");";

  @Rule
  public DataSessionRule sessionRule = new DataSessionRule(DEFAULT_DATASTORE_NAME)
      .access(ComponentDAO.class);

  @Mock
  private Format maven2;

  @Mock
  private Format nuget;

  private DataSession<?> session;

  private ComponentSoftDeleteRepeatableMigrationStep migrationStep;

  @Before
  public void setUp() {
    when(maven2.getValue()).thenReturn("maven2");
    when(nuget.getValue()).thenReturn("nuget");

    migrationStep = new ComponentSoftDeleteRepeatableMigrationStep(Arrays.asList(maven2, nuget));
    session = sessionRule.openSession(DEFAULT_DATASTORE_NAME);
  }

  @After
  public void cleanup() {
    session.close();
  }

  @Test
  public void testChecksum_orderIndependent() {
    ComponentSoftDeleteRepeatableMigrationStep otherOrder =
        new ComponentSoftDeleteRepeatableMigrationStep(Arrays.asList(nuget, maven2));

    assertThat(migrationStep.getChecksum(), is(otherOrder.getChecksum()));
  }

  @Test
  public void testChecksum_differentFormatsProduceDifferentChecksum() {
    ComponentSoftDeleteRepeatableMigrationStep singleFormat =
        new ComponentSoftDeleteRepeatableMigrationStep(Collections.singletonList(maven2));

    assertThat(migrationStep.getChecksum(), not(singleFormat.getChecksum()));
  }

  @Test
  public void testMigrate_createsSoftDeleteIndexes() throws Exception {
    createTable("maven2");
    createTable("nuget");

    try (Connection connection = sessionRule.openConnection(DEFAULT_DATASTORE_NAME)) {
      migrationStep.migrate(connection);

      assertTrue(indexExists(connection, "idx_maven2_component_soft_deleted"));
      assertTrue(indexExists(connection, "idx_maven2_component_active"));
      assertTrue(indexExists(connection, "idx_maven2_component_active_coords"));
      assertTrue(indexExists(connection, "idx_nuget_component_soft_deleted"));
      assertTrue(indexExists(connection, "idx_nuget_component_active"));
      assertTrue(indexExists(connection, "idx_nuget_component_active_coords"));
    }
  }

  @Test
  public void testMigrate_isIdempotent() throws Exception {
    createTable("maven2");

    try (Connection connection = sessionRule.openConnection(DEFAULT_DATASTORE_NAME)) {
      migrationStep.migrate(connection);
      migrationStep.migrate(connection);

      assertTrue(indexExists(connection, "idx_maven2_component_soft_deleted"));
      assertTrue(indexExists(connection, "idx_maven2_component_active"));
      assertTrue(indexExists(connection, "idx_maven2_component_active_coords"));
    }
  }

  @Test
  public void testMigrate_noTables_doesNotThrow() throws Exception {
    try (Connection connection = sessionRule.openConnection(DEFAULT_DATASTORE_NAME)) {
      migrationStep.migrate(connection);
    }
  }

  @Test
  public void testMigrate_skipsTableMissingDeletedOnColumn() throws Exception {
    // Defensive guard: if a table predates the deleted_on column (ordering invariant violated), the step must
    // skip it rather than fail the whole migration.
    createTableWithoutSoftDeleteColumns("maven2");

    try (Connection connection = sessionRule.openConnection(DEFAULT_DATASTORE_NAME)) {
      migrationStep.migrate(connection); // must not throw

      assertFalse(indexExists(connection, "idx_maven2_component_soft_deleted"));
      assertFalse(indexExists(connection, "idx_maven2_component_active"));
      assertFalse(indexExists(connection, "idx_maven2_component_active_coords"));
    }
  }

  private void createTable(final String formatName) throws Exception {
    try (Connection connection = sessionRule.openConnection(DEFAULT_DATASTORE_NAME)) {
      PreparedStatement ps = connection.prepareStatement(CREATE_COMPONENT_TABLE.replaceAll("\\{format\\}", formatName));
      ps.execute();
    }
  }

  private void createTableWithoutSoftDeleteColumns(final String formatName) throws Exception {
    try (Connection connection = sessionRule.openConnection(DEFAULT_DATASTORE_NAME)) {
      PreparedStatement ps =
          connection.prepareStatement(CREATE_COMPONENT_TABLE_NO_SOFT_DELETE.replaceAll("\\{format\\}", formatName));
      ps.execute();
    }
  }

  private boolean indexExists(final Connection conn, final String indexName) throws Exception {
    String sql = "SELECT 1 FROM INFORMATION_SCHEMA.INDEXES WHERE UPPER(INDEX_NAME) = ?";
    try (PreparedStatement statement = conn.prepareStatement(sql)) {
      statement.setString(1, indexName.toUpperCase());
      try (ResultSet results = statement.executeQuery()) {
        return results.next();
      }
    }
  }
}
