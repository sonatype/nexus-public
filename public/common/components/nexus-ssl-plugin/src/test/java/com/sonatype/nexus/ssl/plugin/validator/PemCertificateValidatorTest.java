  private PemCertificateValidator underTest;

  @Before
  public void setUp() {
    underTest = new PemCertificateValidator();
  }

  /*
   * Null value is considered valid (other constraints such as @NotEmpty handle the null/empty case)
   */
  @Test
  public void isValid_nullValue() {
    assertThat(underTest.isValid(null, null), is(true));
  }

  @Test
  public void isValid_validPemCertificate() {
    assertThat(underTest.isValid(VALID_PEM_CERTIFICATE, null), is(true));
  }

  @Test
  public void isValid_invalidPemCertificate() {
    assertThat(underTest.isValid("not-a-valid-certificate", null), is(false));
  }

  @Test
  public void isValid_emptyString() {
    assertThat(underTest.isValid("", null), is(false));
  }
