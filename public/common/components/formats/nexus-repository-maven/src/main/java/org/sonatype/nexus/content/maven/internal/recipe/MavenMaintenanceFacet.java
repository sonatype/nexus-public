package org.sonatype.nexus.content.maven.internal.recipe;

import java.util.ArrayList;
import java.util.List;
import java.util.Set;
import java.util.stream.Stream;

import org.sonatype.nexus.common.collect.NestedAttributesMap;
import org.sonatype.nexus.common.entity.EntityId;
import org.sonatype.nexus.content.maven.MavenContentFacet;
import org.sonatype.nexus.repository.content.Component;
import org.sonatype.nexus.repository.content.browse.BrowseFacet;
import org.sonatype.nexus.repository.content.browse.store.BrowseNodeData;
import org.sonatype.nexus.repository.content.fluent.FluentComponent;
import org.sonatype.nexus.repository.content.maintenance.LastAssetMaintenanceFacet;
import org.sonatype.nexus.repository.content.store.InternalIds;
import org.sonatype.nexus.repository.maven.MavenMetadataRebuildFacet;
import org.sonatype.nexus.repository.maven.MavenPath;
import org.sonatype.nexus.repository.maven.internal.Attributes;
import org.sonatype.nexus.repository.maven.internal.Constants;
import org.sonatype.nexus.repository.maven.internal.Maven2Format;
import org.sonatype.nexus.repository.maven.internal.hosted.metadata.MetadataUtils;

import com.google.common.collect.Sets;
import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.context.annotation.Scope;

import static org.springframework.beans.factory.config.ConfigurableBeanFactory.SCOPE_PROTOTYPE;

/**
 * @since 3.29
 */
@Qualifier(Maven2Format.NAME)
@Scope(SCOPE_PROTOTYPE)
@org.springframework.stereotype.Component
public class MavenMaintenanceFacet
    extends LastAssetMaintenanceFacet
{
  @Override
  public Set<String> deleteComponent(final Component component) {
    return Sets.union(super.deleteComponent(component), mavenContentFacet().deleteMetadataOrFlagForRebuild(component));
  }

  @Override
  public int deleteComponents(final Stream<FluentComponent> components) {
    return mavenContentFacet().deleteComponents(components);
  }

  @Override
  public void afterComponentSoftDeleted(final Component component) {
    mavenContentFacet().deleteMetadataOrFlagForRebuild(component);
  }

  @Override
  public void afterComponentRestored(final Component component) {
    facet(MavenMetadataRebuildFacet.class).rebuildMetadata(
        component.namespace(), component.name(), null, false, false);
    recreateMetadataBrowseNodes(component);
  }

  /**
   * Recreates the browse nodes for the {@code maven-metadata.xml} files (and their checksums) after a component
   * restore — see {@link #metadataPaths} for the group/artifact/version levels covered.
   * <p>
   * These metadata assets are regenerated by {@link MavenMetadataRebuildFacet#rebuildMetadata} but are
   * not owned by the component, so the generic restore browse-node recreation (which only walks the
   * component's own assets) never (re)creates their browse nodes. On the component soft-delete path the
   * metadata assets are hard-deleted, which nulls {@code asset_id} on their existing browse-node rows
   * (FK {@code ON DELETE SET NULL}) while the rows survive and keep holding the unique
   * {@code (repository_id, request_path)} slot. That stale row then blocks re-creation of the node for the
   * rebuilt asset (unique-constraint violation), leaving the metadata downloadable but invisible in Browse.
   * <p>
   * Here we drop the stale node (freeing the unique slot) and add a fresh browse node for the live rebuilt
   * asset, matching the folder-delete/restore behaviour. Multi-version rebuilds are unaffected: the node is
   * simply deleted and re-created against the still-live metadata asset.
   */
  private void recreateMetadataBrowseNodes(final Component component) {
    getRepository().optionalFacet(BrowseFacet.class).ifPresent(browseFacet -> {
      MavenContentFacet contentFacet = mavenContentFacet();
      List<EntityId> assetIds = new ArrayList<>();
      for (String path : metadataPaths(component)) {
        // Free the unique (repository_id, request_path) slot held by any stale/orphaned node so the
        // node for the rebuilt asset can be inserted below.
        browseFacet.getByRequestPath(path)
            .ifPresent(node -> {
              if (node instanceof BrowseNodeData browseNodeData) {
                browseFacet.deleteByNodeId(browseNodeData.getNodeId());
              }
              else {
                log.warn("Unexpected BrowseNode type {} for path '{}'; skipping stale browse-node slot cleanup",
                    node.getClass().getSimpleName(), path);
              }
            });
        contentFacet.assets()
            .path(path)
            .find()
            .ifPresent(asset -> assetIds.add(InternalIds.toExternalId(InternalIds.internalAssetId(asset))));
      }
      if (!assetIds.isEmpty()) {
        browseFacet.addPathsToAssets(assetIds);
      }
    });
  }

  /**
   * The metadata request paths whose browse nodes must be freed/recreated for a restored component:
   * <ul>
   * <li>the group (plugins) level {@code {groupId}/maven-metadata.xml} — generated for plugin groups (the
   * {@code <plugins>} listing) one directory above the artifact; harmless no-op for non-plugin groups,</li>
   * <li>the artifact (GAV) level {@code {groupId}/{artifactId}/maven-metadata.xml},</li>
   * <li>for SNAPSHOT components, the version-level {@code {groupId}/{artifactId}/{baseVersion}/maven-metadata.xml}
   * under the base-version directory.</li>
   * </ul>
   * All of these are regenerated by the metadata rebuild but are not owned by the component, so their browse
   * nodes are not recreated by the generic restore walk.
   */
  private List<String> metadataPaths(final Component component) {
    String groupId = component.namespace();
    String artifactId = component.name();

    // These mirror exactly the metadata levels emitted by the rebuilder (see AbstractMetadataRebuilder):
    // group (plugins) level, artifact (GA) level, and — for SNAPSHOTs — version level. There is no deeper
    // nesting: the group level is keyed off the whole groupId, not each intermediate directory segment.
    List<String> paths = new ArrayList<>();
    paths.addAll(metadataFileVariants(MetadataUtils.metadataPath(groupId, null, null)));
    paths.addAll(metadataFileVariants(MetadataUtils.metadataPath(groupId, artifactId, null)));

    String baseVersion = baseVersion(component);
    if (baseVersion != null && baseVersion.endsWith(Constants.SNAPSHOT_VERSION_SUFFIX)) {
      paths.addAll(metadataFileVariants(MetadataUtils.metadataPath(groupId, artifactId, baseVersion)));
    }
    return paths;
  }

  private static String baseVersion(final Component component) {
    NestedAttributesMap mavenAttributes = component.attributes(Maven2Format.NAME);
    return mavenAttributes == null ? null : mavenAttributes.get(Attributes.P_BASE_VERSION, String.class);
  }

  /**
   * The {@code maven-metadata.xml} plus its four checksum request paths for a metadata {@link MavenPath}.
   * {@link MavenPath} forbids a leading slash, but browse-node request paths and asset paths use one, so the
   * leading slash is added here.
   */
  private static List<String> metadataFileVariants(final MavenPath metadataPath) {
    String base = "/" + metadataPath.getPath();
    return List.of(base, base + ".md5", base + ".sha1", base + ".sha256", base + ".sha512");
  }

  private MavenContentFacet mavenContentFacet() {
    return facet(MavenContentFacet.class);
  }
}
